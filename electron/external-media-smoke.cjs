'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {authRequired}=require('./youtube-auth.cjs');
const {failureError}=require('./task-failure.cjs');
const {DownloadQueue}=require('./model.cjs');
const {collectVimeo}=require('./external-media.cjs');
async function run(collector,check,until,wait){
  const tab=collector.tabs.active,ui=code=>collector.window.webContents.executeJavaScript(code);
  const data=structuredClone(require('./fixtures/behance.json'));
  data.modules.push({id:14,__typename:'EmbedModule',originalEmbed:'<iframe src="https://player.vimeo.com/video/123456"></iframe>'});
  await tab.view.webContents.mainFrame.executeJavaScript(`(()=>{document.getElementById('beconfig-store_state').textContent=${JSON.stringify(JSON.stringify({project:{project:data}}))};const frame=document.createElement('iframe');frame.src='https://player.vimeo.com/video/123456';document.body.append(frame);})()`);
  await until(()=>tab.view.webContents.mainFrame.framesInSubtree.some(frame=>frame.url.includes('/video/123456')),'controlled external frame missing');
  await collector.inspect();
  check('external videos remain skipped until the explicit manual action',collector.state.result.items.length===1&&collector.state.result.skippedExternal===2&&await ui("!!document.getElementById('inspect-external')"));
  await ui("document.querySelector('[data-image=\"1\"]').checked=false");
  const originalEnsure=collector.ensureYouTube,originalRun=collector.runTask,originalAdd=collector.queue.add;
  const calls=[];let authChecks=0,downloadAttempts=0,cancelNext=false,rejectDownload,queued;
  collector.ensureYouTube=async()=>{authChecks++;throw authRequired();};
  collector.runTask=(spec,emit)=>{
    calls.push({site:new URL(spec.url).hostname,command:spec.command,context:spec.context,cookies:fs.readFileSync(spec.cookieFile,'utf8')});
    if(spec.command!=='download')return originalRun(spec,emit);
    downloadAttempts++;
    if(cancelNext)return {promise:new Promise((_,reject)=>{rejectDownload=reject;}),cancel(){rejectDownload(Object.assign(new Error('操作已取消'),{cancelled:true}));}};
    if(downloadAttempts===1)return {promise:Promise.reject(failureError({message:'HTTP Error 403: temporary signed media URL rejected',httpStatus:403},{operation:'download'})),cancel(){}};
    return {promise:Promise.resolve({folder:spec.settings.saveDir,count:1}),cancel(){}};
  };
  try{
    await ui("document.getElementById('inspect-external').click()");
    await until(()=>!tab.state.parsing&&tab.state.result?.externalParsed,'explicit external parse did not finish');
    const itemIndex=tab.state.result.items.findIndex(item=>item.provider==='Vimeo'),item=tab.state.result.items[itemIndex];
    check('native iframe media reaches the real Python Vimeo parser',item?.kind==='video'&&item.formats[0].height===240&&item.duration===6);
    check('YouTube external parsing requires the existing account gate',authChecks===1&&tab.state.result.items.some(item=>item.provider==='YouTube'&&item.kind==='unavailable')&&!calls.some(call=>call.site.includes('youtube')));
    check('external parsing retains existing image selections',await ui("!document.querySelector('[data-image=\"1\"]').checked"));
    check('private player data and signed stream URLs never reach public state',!JSON.stringify(collector.publicState()).includes('privateVimeoStream')&&!JSON.stringify(collector.publicState()).includes('playerConfig'));
    await ui(`document.getElementById('part-select').value='${itemIndex}';document.getElementById('part-select').dispatchEvent(new Event('change',{bubbles:true}))`);
    await until(()=>ui("document.querySelector('[data-preview-image]')?.naturalWidth>0"),'external cover did not decode');
    check('external resource UI shows hosting platform, cover and duration',await ui("document.querySelector('.author').textContent.includes('Vimeo')&&document.querySelector('.media-summary').textContent.includes('00:06')"));
    collector.queue.add=spec=>{queued=spec;return 'controlled-external-task';};
    await collector.download({inspectionId:tab.state.inspectionId,itemIndex,formatId:item.formats[0].id});
    collector.queue.add=originalAdd;
    check('external download binds the chosen module and private context',queued.context.externalSource.key==='14-3'&&queued.referrer.includes('/gallery/123/')&&collector.externalTasks.has(queued));
    await assert.rejects(()=>collector.withCookies({...queued}).promise,/默认不下载/);
    check('copied or renderer-forged task specifications cannot grant external download permission',true);
    queued.context.vimeo.capturedAt=0;
    await collector.withCookies(queued).promise;
    check('expired media is refreshed from its own iframe and a stream rejection retries only once',downloadAttempts===2&&calls.filter(call=>call.command==='download').every(call=>Date.now()-call.context.vimeo.capturedAt<30000));
    check('external worker cookies are scoped to Vimeo rather than the Behance source',calls.every(call=>call.cookies.split('\n').filter(line=>line&&!line.startsWith('#')).every(line=>line.split('\t')[0].endsWith('vimeo.com'))));
    cancelNext=true;
    const queue=new DownloadQueue((spec,emit)=>collector.withCookies(spec,emit),()=>{});
    const id=queue.add(queued,'外部视频取消检查');
    await until(()=>rejectDownload,'external download did not start');queue.cancel(id);
    await until(()=>queue.tasks.find(task=>task.id===id)?.status==='cancelled','external task did not stay cancelled');
    check('cancelling an external download retains the cancelled task state',true);
    const receipt=tab.state.inspectionId;
    collector.switchSite('bilibili');const other=collector.tabs.active,otherReceipt=other.state.inspectionId;
    collector.activateTab(tab.id);
    check('external results survive group switches without changing another group',tab.state.inspectionId===receipt&&other.state.inspectionId===otherReceipt&&tab.state.result.items[itemIndex].provider==='Vimeo');
    const result=tab.state.result;
    const frame=tab.view.webContents.mainFrame.framesInSubtree.find(frame=>frame.url.includes('/video/123456'));
    await frame.executeJavaScript('playerConfig=null');
    const parsing=collector.inspectExternal({inspectionId:receipt});
    await until(()=>tab.state.parsing,'external parse did not enter pending state');
    await collector.invoke('cancel-inspect');await parsing;
    check('cancelling external parsing preserves the completed result and receipt',!tab.state.parsing&&tab.state.result===result&&tab.state.inspectionId===receipt);
    await frame.executeJavaScript("document.body.textContent='此视频不存在。'");
    const refreshed=await collectVimeo(tab.view.webContents,queued.referrer,[collector.externalTasks.get(queued)],{timeout:3000,retryUnready:true});
    check('an unready player retries its own iframe without reloading the project or losing the receipt',refreshed.size===1&&tab.state.inspectionId===receipt&&tab.state.result===result);
  }finally{collector.ensureYouTube=originalEnsure;collector.runTask=originalRun;collector.queue.add=originalAdd;}
}
module.exports={run};
